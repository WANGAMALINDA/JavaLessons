public class User {
    String username;
    String email;
    int ID;
    char gender;

    User(String username, String email) {
        this.username = username;
        this.email = email;
        this.ID = ID;
        this.gender = gender;
    }

    User(String username, String email, int ID) {
        this.username = username;
        this.email = email;
        this.ID = ID;
        this.gender = gender;
    }

    User(String username, String email, int ID, char gender) {
        this.username = username;
        this.email = email;
        this.ID = ID;
        this.gender = gender;
    }
}
